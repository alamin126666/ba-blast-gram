// make_keys.dart — generate the obfuscated native key block for the owner.
//
// The owner supplies api_id/api_hash ONCE (through the secure flow, never
// in plain chat). The builder runs:
//
//     dart scripts/make_keys.dart <api_id> <api_hash>
//
// and pastes the printed block into BOTH native files, replacing the
// OWNER PLACEHOLDER block:
//     android/app/src/main/cpp/telegram_keys.cpp
//     ios/Runner/telegram_keys.c
//
// The XOR key below MUST match kXorKey in telegram_keys.cpp/.c.
// This is obfuscation, not real encryption: it keeps the keys out of
// plain text in Dart code and the repo, and they are decrypted only at
// runtime in native code. Do NOT paste real keys into chat, email, or
// any public place — only into the two native files.

import 'dart:convert';
import 'dart:io';

const String kXorKey = 'BA-BLAST-GRAM-KEY-v1';

String _formatBytes(List<int> bytes) {
  return bytes.map((b) => '0x${b.toRadixString(16).padLeft(2, '0')}').join(', ');
}

List<int> _obfuscate(List<int> plain) {
  final key = utf8.encode(kXorKey);
  return List<int>.generate(
    plain.length,
    (i) => plain[i] ^ key[i % key.length],
  );
}

void main(List<String> args) {
  if (args.length != 2) {
    stderr.writeln('Usage: dart scripts/make_keys.dart <api_id> <api_hash>');
    stderr.writeln('Example: dart scripts/make_keys.dart 123456 '
        'abcdef0123456789abcdef0123456789');
    exit(2);
  }
  final apiId = int.tryParse(args[0]);
  final apiHash = args[1];
  if (apiId == null || apiId <= 0) {
    stderr.writeln('ERROR: api_id must be a positive integer.');
    exit(2);
  }
  if (apiHash.isEmpty || apiHash.length > 128) {
    stderr.writeln('ERROR: api_hash must be 1..128 characters.');
    exit(2);
  }

  // api_id as 8 little-endian bytes.
  final idBytes = List<int>.generate(8, (i) => (apiId >> (8 * i)) & 0xFF);
  final hashBytes = utf8.encode(apiHash);

  stdout.writeln('/* OWNER PLACEHOLDER_BEGIN — generated by '
      'scripts/make_keys.dart. */');
  stdout.writeln('static const uint8_t kApiIdObfuscated[8] = {');
  stdout.writeln('    ${_formatBytes(_obfuscate(idBytes))},');
  stdout.writeln('};');
  stdout.writeln('static const uint8_t kApiHashObfuscated[] = '
      '{${_formatBytes(_obfuscate(hashBytes))}};');
  stdout.writeln('static const uint32_t kApiHashLength = ${hashBytes.length};');
  stdout.writeln('/* OWNER_PLACEHOLDER_END */');
  stdout.writeln();
  stdout.writeln('// Paste the block above into BOTH files, replacing the');
  stdout.writeln('// OWNER PLACEHOLDER block:');
  stdout.writeln('//   android/app/src/main/cpp/telegram_keys.cpp');
  stdout.writeln('//   ios/Runner/telegram_keys.c');
  stdout.writeln('// Then rebuild. Do not paste real keys anywhere else.');
}
